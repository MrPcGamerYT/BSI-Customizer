'use strict';
// Rebuild the committed, independently authored Vulkan SPIR-V. This compiler is
// a development dependency only, never a recipient runtime or a proxy DLL.
// npm install --prefix .cache/shader-build/spirv-tools --save-exact @webgpu/glslang@0.0.15
// node tests/shaders/compile_spirv.cjs [.cache/.../node_modules/@webgpu/glslang]
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const cp = require('node:child_process');
const glslang = require(path.resolve(process.argv[2] || '.cache/shader-build/spirv-tools/node_modules/@webgpu/glslang'))();
const root = path.resolve(__dirname, '../..');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'bsi-spirv-'));
try {
    const emitter = path.join(temporary, 'emit.cpp');
    fs.writeFileSync(emitter, '#include "ShaderSources.h"\n#include <iostream>\nint main(int argc,char**){std::cout<<(argc==1?BsiShaders::vulkanVertexSource():BsiShaders::vulkanFragmentSource());}\n');
    cp.execFileSync(process.env.CXX || 'g++', ['-std=c++17', '-Isrc/shaders', emitter, '-o', path.join(temporary, 'emit')], { cwd: root, stdio: 'inherit' });
    let header = '// Generated by tests/shaders/compile_spirv.cjs using @webgpu/glslang 0.0.15.\n// Source of truth: independently authored shared effect in ShaderSources.h.\n#pragma once\n#include <cstdint>\nnamespace BsiShaders {\n';
    for (const [name, stage, args] of [['vulkanVertexSpirv', 'vertex', []], ['vulkanFragmentSpirv', 'fragment', ['fragment']]]) {
        const text = cp.execFileSync(path.join(temporary, 'emit'), args, { encoding: 'utf8' });
        const words = glslang.compileGLSL(text, stage, false, '1.0');
        header += `inline constexpr std::uint32_t ${name}[] = {\n`;
        for (let index = 0; index < words.length; index += 8) header += '    ' + Array.from(words.slice(index, index + 8), v => '0x' + v.toString(16).padStart(8, '0') + 'u').join(',') + ',\n';
        header += '};\n';
        console.log(`${name}: ${words.length * 4} bytes, SPIR-V 1.0`);
    }
    header += '} // namespace BsiShaders\n';
    const output = path.join(root, 'src/shaders/VulkanSpirv.h');
    if (process.env.BSI_CHECK_GENERATED) {
        if (fs.readFileSync(output, 'utf8') !== header) throw new Error('Committed Vulkan SPIR-V differs from the current shared source. Rebuild it.');
    } else fs.writeFileSync(output, header);
} finally { fs.rmSync(temporary, { recursive: true, force: true }); }
