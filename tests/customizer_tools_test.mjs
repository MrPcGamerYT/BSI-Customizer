import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read = p => fs.readFileSync(new URL('../' + p, import.meta.url), 'utf8');
const catalog = {}; vm.createContext(catalog);
vm.runInContext(read('src/qml/ToolCatalog.js').replace('.pragma library',''), catalog);
const original = JSON.stringify(catalog.tools);
for (const tool of catalog.tools) {
  assert.ok((Number.isInteger(tool.route) && tool.route >= 0 && tool.route <= 12) || (Number.isInteger(tool.tab) && tool.tab >= 0 && tool.tab <= 2));
}
assert.equal(catalog.search('').length, 18);
assert.equal(catalog.search('  BACKUP  ')[0].route, 11);
assert.equal(catalog.search('fps')[0].route, 3);
assert.equal(catalog.search('round corners')[0].route, 8);
assert.equal(catalog.search('reduced motion')[0].tab, 0);
assert.equal(catalog.search('impossiblequery').length, 0);
assert.equal(catalog.search('<script>').length, 0);
assert.equal(JSON.stringify(catalog.tools), original);
assert.equal(catalog.operation({kind:'theme',edits:{base:'#000',text:'#fff'}}).detail, '2 color edit(s): base, text');
assert.ok(!JSON.stringify(catalog.operation({kind:'resource',path:'icon.svg',data:'PRIVATE-BINARY'})).includes('PRIVATE-BINARY'));
assert.equal(catalog.bytes(undefined), 'Not recorded');
assert.equal(catalog.bytes(null), 'Not recorded');
assert.equal(catalog.bytes(-1), 'Not recorded');
assert.equal(catalog.bytes(1024), '1.0 KiB');
assert.equal(catalog.sameTarget('C:\\Player\\HD-Player.exe','c:/player/hd-player.exe'), true);
assert.equal(catalog.sameTarget('/home/User/a.exe','/home/user/a.exe'), false);
assert.equal(catalog.sameTarget('',''), false);
const rows = [{id:'a',path:'C:/One/HD-Player.exe',state:'applied',time:'2026-10-25'}, {id:'b',path:'C:/Two/HD-Player.exe',state:'restored',time:'2026-10-24'}];
assert.equal(catalog.history(rows,'','c:/one/hd-player.exe').length,1);
assert.equal(catalog.history(rows,'restored','')[0].id,'b');
assert.equal(catalog.history(rows,'applied 2026-10-24','').length,0);
const finder = read('src/qml/components/ToolFinder.qml');
assert.ok(!/backend\.|workspace\(|scanResources\(/.test(finder), 'finder must navigate, never invoke engines');
assert.ok(finder.includes('if (!authorized ||'));
assert.ok(finder.includes('onAuthorizedChanged: if (!authorized) close()'));
const workspace = read('src/qml/pages/WorkspacePage.qml');
assert.ok(workspace.includes('reviewAcknowledged.checked && stillValid()'));
assert.ok(workspace.includes('reviewedPath === backend.exePath'));
assert.ok(workspace.includes('outputSha256: reviewedOutput'));
assert.ok(workspace.includes('onWorkspaceChanged() { page.plan = ({}); applyDialog.close(); }'));
const backups = read('src/qml/pages/BackupsPage.qml');
assert.ok(!backups.includes('Component.onCompleted'));
assert.ok(backups.includes('backend.exePath !== page.restoreTarget'));
assert.ok(backups.includes('pendingRestore = JSON.parse(JSON.stringify(selectedEntry))'));
assert.ok(backups.includes('backend.workspace("restore", {id: page.pendingRestore.id})'));
console.log('PASS: pure navigation search, valid routes, summaries without binary payloads, textual target filtering, frozen review/restore guards and manual history loading.');
