const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const context={window:{},Intl,Set,Map};vm.createContext(context);
vm.runInContext(fs.readFileSync('src/web/resource-search.js','utf8'),context);
context.BsiResourceSearch=context.window.BsiResourceSearch;
vm.runInContext(fs.readFileSync('src/web/resource-workbench.js','utf8'),context);
const model=context.window.BsiResourceWorkbench.create();
const rows=[{index:4,path:'images/z10.svg',format:'SVG',kind:'svg',text:true,size:10},{index:9,path:'images/z2.png',format:'PNG',kind:'image',size:20},{index:12,path:'qml/window.qml',format:'QML',kind:'text',text:true,size:40},{index:7,path:'fonts\\bold.ttf',format:'TTF',kind:'binary',size:100},{index:22,path:'images/<svg onload=x>.svg',format:'SVG',kind:'svg',text:true,size:3}];
model.setRows(rows);
assert.equal(model.children('').length,3);
assert.deepEqual(Array.from(model.query({folder:'images',kind:2}),r=>r.index),[22,4]);
assert.deepEqual(Array.from(model.query({text:'min:15b',sort:'size'}),r=>r.index),[7,12,9]);
assert.deepEqual(Array.from(model.query({kind:5}),r=>r.index),[7]);
model.bookmark(rows[0].path);assert.deepEqual(Array.from(model.query({favorites:true}),r=>r.index),[4]);
model.check(rows[1].path);assert.ok(model.checked.has(rows[1].path));
model.setRows(rows.slice(1));assert.equal(model.bookmarks.size,0);assert.equal(model.checked.size,0);
const many=Array.from({length:20000},(_,index)=>({index,path:`assets/pool-${index%64}/file-${index}.qml`,kind:'text',format:'QML',text:true,size:index}));
const start=performance.now();model.setRows(many);
for(let i=0;i<40;i++)model.query({text:'file-'+i,kind:3,sort:i%2?'path':'size'});
assert.equal(model.children('assets').length,64);
assert.ok(performance.now()-start<5000,'20k metadata rows should remain bounded and practical');
model.reset();assert.equal(model.query().length,0);assert.equal(model.checked.size,0);
console.log('PASS: resource folders, stable native indexes, natural sorting, query/kind/size filters, bookmarks, selection reset and 20k-row metadata workload.');
