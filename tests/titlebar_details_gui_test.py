"""Render the production C++ title-details rewrite; keep Settings labels visible.

The fixture files must be generated by tests/titlebar_details_test.cpp first.
No mirrored Python patching algorithm and no emulator process are used.
"""
import os
from pathlib import Path
import subprocess

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ.setdefault("QT_QUICK_BACKEND", "software")
if os.environ.get("BSI_TEST_QT_API") == "PyQt5":
    from PyQt5.QtCore import QMetaObject, QPointF, Qt
    from PyQt5.QtGui import QGuiApplication
    from PyQt5.QtQml import QQmlComponent, QQmlEngine, QQmlExpression
    from PyQt5.QtQuick import QQuickItem, QQuickWindow
    from PyQt5.QtTest import QTest
else:
    os.environ.setdefault("QSG_RHI_BACKEND", "software")
    from PySide6.QtCore import QMetaObject, QPointF, Qt
    from PySide6.QtGui import QGuiApplication
    from PySide6.QtQml import QQmlComponent, QQmlEngine, QQmlExpression
    from PySide6.QtQuick import QQuickItem, QQuickWindow
    from PySide6.QtTest import QTest


def children(item):
    pending = list(item.childItems())
    while pending:
        child = pending.pop()
        yield child
        pending.extend(child.childItems())


def main():
    root = Path(os.environ["BSI_TITLE_DETAILS_FIXTURES"])
    if os.environ.get("BSI_TEST_QT_API") != "PyQt5":
        # Parse the real rewritten topbar too, without resolving/executing OEM
        # modules. The synthetic scene below then verifies layout and painting.
        import PySide6
        formatter = Path(PySide6.__file__).parent / ("qmlformat.exe" if os.name == "nt" else "qmlformat")
        native = root / "native-PlrTopbar-hidden.qml"
        assert native.is_file(), "the production rewrite of the native topbar was not generated"
        for path in sorted(root.glob("*.qml")):
            parsed = subprocess.run([str(formatter), str(path)], stdout=subprocess.DEVNULL,
                                    stderr=subprocess.PIPE, text=True)
            assert parsed.returncode == 0, f"{path}: {parsed.stderr}"
    app = QGuiApplication.instance() or QGuiApplication([])
    engine = QQmlEngine()
    warnings = []
    engine.warnings.connect(lambda errors: warnings.extend(e.toString() for e in errors))
    expected = ["Performance", "CPU allocation", "Memory allocation", "Version", "Instance name", "Display"]
    for variant in ("grouped", "flat", "callback", "formerly-blank"):
        component = QQmlComponent(engine, str((root / (variant + "-hidden.qml")).resolve()))
        window = component.create()
        assert window is not None, "\n".join(e.toString() for e in component.errors())
        QTest.qWait(80)
        tree = {i.objectName(): i for i in children(window.contentItem()) if i.objectName()}
        bar, name = tree["playerTitleBar"], tree["playerName"]
        for height in (32, 40, 48, 64):
            assert window.setProperty("barHeight", height)
            for width in (720, 1068, 1440):
                window.resize(width, 430)
                QMetaObject.invokeMethod(window, "reloadDetails")
                QTest.qWait(35)
                assert not tree["versionLabel"].isVisible(), "version reappeared after a native-style reload"
                assert not tree["instanceLabel"].isVisible(), "instance label reappeared after a native-style reload"
                assert name.isVisible() and name.property("text") == "BlueStacks App Player"
                alignment = QQmlExpression(QQmlEngine.contextForObject(name), name, "verticalAlignment === Text.AlignVCenter")
                aligned = alignment.evaluate()
                assert not alignment.hasError() and (aligned[0] if isinstance(aligned, tuple) else aligned), \
                    "name glyphs must align vertically inside their item"
                centre = name.mapToItem(bar, QPointF(name.width() / 2, name.height() / 2)).y()
                assert abs(centre - bar.height() / 2) <= .6, (variant, height, width, centre)
                for index, text in enumerate(expected):
                    label = tree["settingsText" + str(index)]
                    assert label.isVisible() and label.property("text") == text, f"Settings text vanished: {text}"
                    assert label.property("color").alpha() == 255 and label.opacity() == 1
                assert tree["settingsCheck"].isVisible() and tree["settingsCheck"].isEnabled()
                assert tree["settingsButton"].isVisible() and tree["settingsButton"].isEnabled()
        before = window.property("callbackCount")
        button = tree["settingsButton"]
        point = button.mapToScene(QPointF(button.width() / 2, button.height() / 2)).toPoint()
        QTest.mouseClick(window, Qt.MouseButton.LeftButton, Qt.KeyboardModifier.NoModifier, point)
        QTest.qWait(20)
        assert window.property("callbackCount") > before, "Settings button stopped accepting physical clicks"
        if variant == "callback":
            assert before > 0, "the native visibility callback was discarded"
        window.resize(1068, 430)
        window.setProperty("barHeight", 48)
        QTest.qWait(50)
        # Qt 5's software backend requires the asynchronous item capture path.
        capture = window.contentItem().grabToImage()
        from importlib import import_module
        spy = import_module("PyQt5.QtTest" if os.environ.get("BSI_TEST_QT_API") == "PyQt5" else "PySide6.QtTest").QSignalSpy(capture.ready)
        if capture.image().isNull():
            assert spy.wait(2000)
        assert not capture.image().isNull()
        frame = capture.image()
        for index, text in enumerate(expected):
            label = tree["settingsText" + str(index)]
            origin = label.mapToScene(QPointF(0, 0))
            ink = 0
            for y in range(round(origin.y()), min(frame.height(), round(origin.y() + label.height()))):
                for x in range(round(origin.x()), min(frame.width(), round(origin.x() + label.width()))):
                    colour = frame.pixelColor(x, y)
                    if all(abs(getattr(colour, c)() - v) <= 2 for c, v in (("red", 231), ("green", 237), ("blue", 245))):
                        ink += 1
            assert ink >= 5, f"Settings text did not actually paint: {text}"
        if variant == "grouped":
            assert capture.image().save(str(root / ("title-details-" + ("qt5" if os.environ.get("BSI_TEST_QT_API") == "PyQt5" else "qt6") + ".png")))
        window.hide()
        window.deleteLater()
        QTest.qWait(10)
    assert not warnings, "\n".join(warnings)
    print("PASS: production C++ title-details output hides version + instance, vertically centres the remaining name, preserves native callbacks/Settings text and physical Settings-button input in Qt " + ("5" if os.environ.get("BSI_TEST_QT_API") == "PyQt5" else "6"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
