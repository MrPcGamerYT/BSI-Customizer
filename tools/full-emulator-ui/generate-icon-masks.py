"""Generate synchronous tintable indexed-PNG masks from the reviewed glyph PNGs.
Python standard library only; no runtime rasterizer, SVG plugin or Canvas needed.
"""
import json
from pathlib import Path
import struct
import zlib

ROOT=Path(__file__).resolve().parents[2]
ASSETS=ROOT/'assets/full-emulator-ui'


def alpha_png(path):
    data=path.read_bytes();assert data[:8]==b'\x89PNG\r\n\x1a\n'
    at=8;compressed=b''
    while at<len(data):
        size=struct.unpack('>I',data[at:at+4])[0];kind=data[at+4:at+8];body=data[at+8:at+8+size];at+=size+12
        if kind==b'IHDR':width,height,depth,color,_,_,interlaced=struct.unpack('>IIBBBBB',body)
        if kind==b'IDAT':compressed+=body
    assert depth==8 and color==6 and not interlaced,(path,depth,color,interlaced)
    raw=zlib.decompress(compressed);stride=width*4;previous=bytearray(stride);out=bytearray();at=0
    for _ in range(height):
        mode=raw[at];at+=1;row=bytearray(raw[at:at+stride]);at+=stride
        for i in range(stride):
            a=row[i-4] if i>=4 else 0;b=previous[i];c=previous[i-4] if i>=4 else 0
            if mode==1:predict=a
            elif mode==2:predict=b
            elif mode==3:predict=(a+b)//2
            elif mode==4:
                p=a+b-c;pa=abs(p-a);pb=abs(p-b);pc=abs(p-c)
                predict=a if pa<=pb and pa<=pc else b if pb<=pc else c
            else:assert mode==0;predict=0
            row[i]=(row[i]+predict)&255
        out.append(0);out.extend(row[3::4]);previous=row
    return [width,height,zlib.compress(bytes(out),9).decode('latin1')]


def main():
    masks={path.relative_to(ASSETS).as_posix():alpha_png(path) for path in sorted(ASSETS.rglob('*.png'))}
    source='''.pragma library
// Generated by tools/full-emulator-ui/generate-icon-masks.py. PNG alpha coverage
// is precompressed offline. At runtime only the 256-entry palette is changed;
// Image.asynchronous=false decodes the exact chosen tint before first paint.
var masks = MASK_DATA;
var cache = {};
var order = [];
var crcTable = [];
for(var n=0;n<256;++n){var c=n;for(var k=0;k<8;++k)c=(c&1)?0xedb88320^(c>>>1):c>>>1;crcTable[n]=c>>>0;}
function bytes32(n){return String.fromCharCode((n>>>24)&255,(n>>>16)&255,(n>>>8)&255,n&255);}
function chunk(type,data){var value=type+data,crc=0xffffffff;for(var i=0;i<value.length;++i)crc=crcTable[(crc^value.charCodeAt(i))&255]^(crc>>>8);return bytes32(data.length)+value+bytes32((crc^0xffffffff)>>>0);}
var transparency="";
for(var a=0;a<256;++a)transparency+=String.fromCharCode(a);
var alphaChunk=chunk("tRNS",transparency);
var endChunk=chunk("IEND","");
// Qt.btoa converts QString through UTF-8, corrupting binary PNG bytes >=128.
// Encode the Latin-1 byte string ourselves instead (also works on Qt 5.15).
function base64(data){
    var alphabet="ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/",out="";
    for(var i=0;i<data.length;i+=3){var a=data.charCodeAt(i),b=i+1<data.length?data.charCodeAt(i+1):0,c=i+2<data.length?data.charCodeAt(i+2):0;
        out+=alphabet[a>>>2]+alphabet[((a&3)<<4)|(b>>>4)]+(i+1<data.length?alphabet[((b&15)<<2)|(c>>>6)]:"=")+(i+2<data.length?alphabet[c&63]:"=");}
    return out;
}
function colored(source,tint){
    var parts=decodeURIComponent(String(source)).split("/"),path=parts.slice(-2).join("/");
    if(!masks[path])path=parts.slice(-3).join("/");
    var mask=masks[path];if(!mask)return String(source);
    var r=Math.round(tint.r*255),g=Math.round(tint.g*255),b=Math.round(tint.b*255);
    var key=path+":"+r+","+g+","+b;
    if(cache[key])return cache[key];
    var palette="",pixel=String.fromCharCode(r,g,b);
    for(var i=0;i<256;++i)palette+=pixel;
    var png="\\x89PNG\\r\\n\\x1a\\n"+chunk("IHDR",bytes32(mask[0])+bytes32(mask[1])+"\\x08\\x03\\x00\\x00\\x00")+chunk("PLTE",palette)+alphaChunk+chunk("IDAT",mask[2])+endChunk;
    var result="data:image/png;base64,"+base64(png);
    cache[key]=result;order.push(key);
    if(order.length>128)delete cache[order.shift()];
    return result;
}
'''.replace('MASK_DATA',json.dumps(masks,ensure_ascii=True,separators=(',',':')))
    (ASSETS/'IconMasks.js').write_text(source,encoding='utf-8')
    print('Generated',len(masks),'indexed PNG alpha masks; bounded 128-entry runtime tint cache.')


if __name__=='__main__':main()
